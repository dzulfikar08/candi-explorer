/**
 * Generates src/map/land.ts: SVG path data for Indonesia and its neighbours from Natural Earth
 * 1:50m Admin 0 countries (public domain, https://www.naturalearthdata.com).
 *
 *   bun scripts/build-map.ts [path/to/ne_50m_admin_0_countries.geojson]
 *
 * Without an argument it downloads the file. Coordinates are plain longitude and negated
 * latitude in degrees (equirectangular; Indonesia straddles the equator, so the distortion is
 * small), simplified with Douglas–Peucker and rounded to 0.01°.
 */

const SOURCE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson";
const NEIGHBOURS = ["Malaysia", "Brunei", "Singapore", "East Timor", "Papua New Guinea", "Philippines", "Australia", "Thailand"];
/** Map frame in degrees: west, east, south, north. */
const FRAME = { west: 92, east: 143, south: -13, north: 9 };

type Ring = [number, number][];
interface Feature {
  properties: { ADMIN: string };
  geometry: { type: "Polygon"; coordinates: Ring[] } | { type: "MultiPolygon"; coordinates: Ring[][] };
}

function perpendicular(p: [number, number], a: [number, number], b: [number, number]): number {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const len = Math.hypot(dx, dy);
  if (len === 0) return Math.hypot(p[0] - a[0], p[1] - a[1]);
  return Math.abs(dy * p[0] - dx * p[1] + b[0] * a[1] - b[1] * a[0]) / len;
}

function simplify(points: Ring, tolerance: number): Ring {
  if (points.length < 3) return points;
  let max = 0;
  let index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const d = perpendicular(points[i], points[0], points[points.length - 1]);
    if (d > max) {
      max = d;
      index = i;
    }
  }
  if (max <= tolerance) return [points[0], points[points.length - 1]];
  return [...simplify(points.slice(0, index + 1), tolerance).slice(0, -1), ...simplify(points.slice(index), tolerance)];
}

function area(ring: Ring): number {
  let a = 0;
  for (let i = 0; i < ring.length; i++) {
    const [x1, y1] = ring[i];
    const [x2, y2] = ring[(i + 1) % ring.length];
    a += x1 * y2 - x2 * y1;
  }
  return Math.abs(a) / 2;
}

function toPath(features: Feature[], tolerance: number, minArea: number): string {
  const parts: string[] = [];
  for (const f of features) {
    const polygons = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
    for (const polygon of polygons) {
      for (const ring of polygon) {
        const visible = ring.some(([lon, lat]) => lon > FRAME.west && lon < FRAME.east && lat > FRAME.south && lat < FRAME.north);
        if (!visible || area(ring) < minArea) continue;
        const simple = simplify(ring, tolerance);
        if (simple.length < 4) continue;
        const points = simple.slice(0, -1).map(([lon, lat]) => `${lon.toFixed(2)} ${(-lat).toFixed(2)}`);
        parts.push(`M${points.join("L")}Z`);
      }
    }
  }
  return parts.join("");
}

const file = process.argv[2];
const geojson: { features: Feature[] } = file ? await Bun.file(file).json() : await (await fetch(SOURCE)).json();
const indonesia = geojson.features.filter((f) => f.properties.ADMIN === "Indonesia");
const neighbours = geojson.features.filter((f) => NEIGHBOURS.includes(f.properties.ADMIN));
if (indonesia.length !== 1) throw new Error("Indonesia not found in the source file");

const out = `// Generated by scripts/build-map.ts from Natural Earth 1:50m Admin 0 countries (public domain).
// Do not edit by hand. Units: x = longitude, y = −latitude, in degrees.

/** Map frame: west, north (as −latitude), width and height in degrees. */
export const FRAME = { x: ${FRAME.west}, y: ${-FRAME.north}, width: ${FRAME.east - FRAME.west}, height: ${FRAME.north - FRAME.south} } as const;

export const INDONESIA = "${toPath(indonesia, 0.015, 0.0004)}";

export const NEIGHBOURS = "${toPath(neighbours, 0.04, 0.01)}";
`;
await Bun.write(new URL("../src/map/land.ts", import.meta.url), out);
console.log(`wrote src/map/land.ts (${(out.length / 1024).toFixed(1)} KB)`);
